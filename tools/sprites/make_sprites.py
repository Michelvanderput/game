#!/usr/bin/env python3
"""Sprites as code.

Reads tools/sprites/palette.txt and every tools/sprites/*.txt sprite grid, then writes:
  - assets/art/palette.png        (one pixel per palette colour, in file order)
  - assets/art/export/<name>.png  (one PNG per sprite file)
  - src/core/palette.gd           (palette colours as GDScript constants)

Sprite file format: one character per pixel, '.' is transparent, letters come from
palette.txt. Lines starting with '#' are comments. Blank lines separate frames; frames
are placed side by side in one horizontal strip (all frames must be the same size).

Usage:
  python tools/sprites/make_sprites.py              # build everything
  python tools/sprites/make_sprites.py --preview DIR --scale 8   # also write enlarged previews
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SPRITE_DIR = ROOT / "tools" / "sprites"
PALETTE_SRC = SPRITE_DIR / "palette.txt"
PALETTE_PNG = ROOT / "assets" / "art" / "palette.png"
EXPORT_DIR = ROOT / "assets" / "art" / "export"
PALETTE_GD = ROOT / "src" / "core" / "palette.gd"

TRANSPARENT = "."


class SpriteError(Exception):
    pass


def read_palette(path: Path) -> list[tuple[str, tuple[int, int, int], str]]:
    entries: list[tuple[str, tuple[int, int, int], str]] = []
    for line_no, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3 or len(parts[0]) != 1 or len(parts[1]) != 6:
            raise SpriteError(f"{path.name}:{line_no}: expected '<letter> <rrggbb> <NAME>'")
        letter, hex_code, name = parts
        if letter == TRANSPARENT:
            raise SpriteError(f"{path.name}:{line_no}: '.' is reserved for transparency")
        rgb = tuple(int(hex_code[i : i + 2], 16) for i in (0, 2, 4))
        entries.append((letter, rgb, name))  # type: ignore[arg-type]
    if len({e[0] for e in entries}) != len(entries):
        raise SpriteError(f"{path.name}: duplicate letters")
    return entries


def read_frames(path: Path) -> list[list[str]]:
    frames: list[list[str]] = []
    current: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if line.startswith("#"):
            continue
        if not line:
            if current:
                frames.append(current)
                current = []
            continue
        current.append(line)
    if current:
        frames.append(current)
    if not frames:
        raise SpriteError(f"{path.name}: no pixels")
    width, height = len(frames[0][0]), len(frames[0])
    for index, frame in enumerate(frames):
        if len(frame) != height or any(len(row) != width for row in frame):
            raise SpriteError(f"{path.name}: frame {index} is not {width}x{height}")
    return frames


def render(path: Path, colours: dict[str, tuple[int, int, int]]) -> Image.Image:
    frames = read_frames(path)
    width, height = len(frames[0][0]), len(frames[0])
    image = Image.new("RGBA", (width * len(frames), height), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        for y, row in enumerate(frame):
            for x, char in enumerate(row):
                if char == TRANSPARENT:
                    continue
                if char not in colours:
                    raise SpriteError(f"{path.name}: unknown palette letter '{char}' at frame {index}, ({x}, {y})")
                image.putpixel((index * width + x, y), (*colours[char], 255))
    return image


def write_palette_gd(entries: list[tuple[str, tuple[int, int, int], str]]) -> None:
    lines = [
        "# GENERATED by tools/sprites/make_sprites.py from tools/sprites/palette.txt. Do not edit by hand.",
        "class_name Palette",
        "extends RefCounted",
        "",
    ]
    for _, (r, g, b), name in entries:
        lines.append(f"const {name}: Color = Color({r / 255:.6f}, {g / 255:.6f}, {b / 255:.6f})")
    PALETTE_GD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--preview", type=Path, help="also write enlarged previews to this folder")
    parser.add_argument("--scale", type=int, default=8, help="preview scale (default 8)")
    args = parser.parse_args()

    try:
        entries = read_palette(PALETTE_SRC)
        colours = {letter: rgb for letter, rgb, _ in entries}

        PALETTE_PNG.parent.mkdir(parents=True, exist_ok=True)
        palette_image = Image.new("RGBA", (len(entries), 1))
        for x, (_, rgb, _) in enumerate(entries):
            palette_image.putpixel((x, 0), (*rgb, 255))
        palette_image.save(PALETTE_PNG)
        write_palette_gd(entries)

        EXPORT_DIR.mkdir(parents=True, exist_ok=True)
        sprites = sorted(p for p in SPRITE_DIR.glob("*.txt") if p.name != PALETTE_SRC.name)
        for sprite_path in sprites:
            image = render(sprite_path, colours)
            out = EXPORT_DIR / f"{sprite_path.stem}.png"
            image.save(out)
            print(f"wrote {out.relative_to(ROOT)} ({image.width}x{image.height})")
            if args.preview:
                args.preview.mkdir(parents=True, exist_ok=True)
                big = image.resize((image.width * args.scale, image.height * args.scale), Image.NEAREST)
                big.save(args.preview / f"{sprite_path.stem}_x{args.scale}.png")
    except SpriteError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(f"wrote {PALETTE_PNG.relative_to(ROOT)} and {PALETTE_GD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
